// Employee documents. Bytes live on disk (never in the database), under a folder per organization, with a random name.
// Nothing the user types ever becomes part of a path.
import { randomUUID } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

export const DOC_CATEGORIES = ["Identification", "Contract", "Certificate", "Education", "Medical", "Other"] as const;
export const MAX_BYTES = Number(process.env.DOCUMENT_MAX_MB ?? 5) * 1024 * 1024;

const root = () => path.resolve(process.cwd(), process.env.STORAGE_DIR ?? "storage");

// Decide the real type from the first bytes. The browser's file name and type are not trusted.
export function sniffType(b: Uint8Array): { mime: string; ext: string } | null {
  if (b.length >= 5 && String.fromCharCode(...b.slice(0, 5)) === "%PDF-") return { mime: "application/pdf", ext: "pdf" };
  if (b.length >= 8 && [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a].every((v, i) => b[i] === v)) return { mime: "image/png", ext: "png" };
  if (b.length >= 3 && b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff) return { mime: "image/jpeg", ext: "jpg" };
  return null;
}

export async function saveFile(organizationId: string, bytes: Uint8Array): Promise<string> {
  const key = `${organizationId}/${randomUUID()}`;
  const full = path.join(root(), key);
  await mkdir(path.dirname(full), { recursive: true });
  await writeFile(full, bytes);
  return key;
}

export async function readStored(storageKey: string, organizationId: string): Promise<Buffer | null> {
  // Keys are generated by us, but check anyway: right organization folder, no path tricks.
  if (!/^[a-z0-9]+\/[0-9a-f-]{36}$/.test(storageKey) || !storageKey.startsWith(`${organizationId}/`)) return null;
  try {
    return await readFile(path.join(root(), storageKey));
  } catch {
    return null;
  }
}

// A name safe to show and to send in a header.
export const safeName = (s: string) => s.replace(/[^\w.\- ()]+/g, "_").slice(0, 120) || "document";
